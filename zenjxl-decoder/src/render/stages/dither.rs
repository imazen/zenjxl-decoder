//! Ordered (blue-noise) dithering for 8-bit output, as libjxl does in
//! `render_pipeline/stage_write.cc` (`MakeUnsigned`) and jxl-rs since #841.
//!
//! Quantising a float sample to 8 bits by rounding alone turns smooth
//! gradients into visible bands; adding a fixed zero-mean noise pattern
//! below half a code before rounding breaks those bands up into high-frequency
//! noise the eye averages out. The table is indexed by *absolute* image
//! position and output channel, so the result is deterministic, identical for
//! streamed and one-shot decodes, and -- with the same table and indexing --
//! bit-for-bit what `djxl` emits wherever the float pipelines agree. An exact
//! 8-bit value is never moved (|dither| < 0.5), so lossless 8-bit content is
//! untouched.

use jxl_simd::{F32SimdVec, SimdDescriptor};

/// Table period along both axes.
pub(crate) const DITHER_PERIOD: usize = 32;

/// Dither offset (in output codes) for the `len` samples starting at absolute
/// `x` on row `y` of output channel `channel`, where `len <= 16`.
///
/// Rows are stored padded to 48 entries (the first 16 repeated) so a 16-lane
/// load starting anywhere in `0..32` wraps around horizontally without a
/// modulo per lane.
#[inline(always)]
pub(crate) fn dither_vec<D: SimdDescriptor>(
    d: D,
    (x, y): (usize, usize),
    channel: usize,
) -> D::F32Vec {
    debug_assert!(D::F32Vec::LEN <= 16);
    let dx = (x + channel * 23) % DITHER_PERIOD;
    let dy = (y + channel * 13) % DITHER_PERIOD;
    D::F32Vec::load(d, &DITHER_TABLE[dy][dx..])
}

