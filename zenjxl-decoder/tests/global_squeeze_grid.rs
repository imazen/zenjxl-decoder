fn bytes(hex: &str) -> Vec<u8> {
    hex.as_bytes()
        .chunks_exact(2)
        .map(|pair| {
            let digit = |v: u8| (v as char).to_digit(16).unwrap() as u8;
            (digit(pair[0]) << 4) | digit(pair[1])
        })
        .collect()
}
#[path = "support/global_squeeze_transposed.rs"]
mod transposed;
fn check(
    encoded: &[u8],
    tile: &[u8],
    width: usize,
    height: usize,
    tile_width: usize,
    tile_height: usize,
) {
    let parallel_modes: &[bool] = if cfg!(feature = "threads") {
        &[false, true]
    } else {
        &[false]
    };
    for &parallel in parallel_modes {
        for dither in [false, true] {
            let options = zenjxl_decoder::api::JxlDecoderOptions::default()
                .with_parallel(parallel)
                .with_dither_u8(dither);
            let decoded = zenjxl_decoder::decode_with(encoded, options).unwrap();
            assert_eq!(
                (decoded.width, decoded.height, decoded.channels),
                (width, height, 2)
            );
            assert!(decoded.is_grayscale);
            assert_eq!(decoded.data.len(), width * height * 2);
            for (index, pixel) in decoded.data.chunks_exact(2).enumerate() {
                let (x, y) = (index % width, index / width);
                assert_eq!(
                    pixel[0],
                    tile[(y % tile_height) * tile_width + x % tile_width],
                    "gray sample {index}"
                );
                assert_eq!(pixel[1], 255, "opaque alpha {index}");
            }
        }
    }
}
#[test]
fn global_squeeze_inputs_survive_a_larger_intermediate_channel() {
    check(
        &bytes(STREAM_HEX),
        &bytes(SOURCE_PERIOD_HEX),
        2,
        16449,
        2,
        1105,
    );
}
#[test]
fn transposed_global_squeeze_inputs_preserve_every_source_code() {
    check(
        &bytes(transposed::STREAM_HEX),
        &bytes(transposed::SOURCE_TILE_HEX),
        16449,
        2,
        1118,
        2,
    );
}
